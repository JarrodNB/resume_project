# Check live providers through durable interview operations and one persistent budget ledger.
# Explicit opt-in only. Stops at the first unknown cost or failed operation; never retries.
require "net/http"
require "digest"

raise "Explicit local paid verification only" unless Rails.env.development? && ENV["INTERVIEW_PAID_VERIFICATION"] == "true"

def ledger(label)
  rows = InterviewVerificationReservation.all
  puts "LEDGER #{label}: count=#{rows.count} known_microdollars=#{rows.sum(:actual_microdollars)} unresolved=#{rows.where(actual_microdollars: nil).count}"
end

def checked(result)
  raise "Application rejected verification request" unless result.success?
  result.value
end

def await_paid(operation)
  started = Process.clock_gettime(Process::CLOCK_MONOTONIC)
  loop do
    operation.reload
    if operation.failure_code.present?
      ledger("failure")
      raise "STOP: execution failure (#{operation.failure_code})"
    end
    # A live in-flight reservation is also unresolved. Wait for terminal operation
    # before inspecting it; never admit another operation while this one is pending.
    if operation.accepted? || operation.failed?
      sleep 0.5 # usage reconciliation follows atomic dialogue acceptance
      ledger(operation.kind)
      raise "STOP: unknown provider cost" if InterviewVerificationReservation.where(actual_microdollars: nil).exists?
      raise "STOP: provider operation failed (#{operation.failure_code})" if operation.failed?
      puts "LATENCY #{operation.kind}: #{(Process.clock_gettime(Process::CLOCK_MONOTONIC) - started).round(2)} seconds"
      return
    end
    raise "STOP: operation deadline exceeded" if Process.clock_gettime(Process::CLOCK_MONOTONIC) - started > 150
    sleep 0.2
  end
end

$stdout.sync = true
ledger("before")
raise "STOP: pre-existing unknown provider cost" if InterviewVerificationReservation.where(actual_microdollars: nil).exists?
user = User.create!(email: "spoken-paid-#{SecureRandom.hex(6)}@example.invalid", password: SecureRandom.base64(30), confirmed_at: Time.current,
  summary: "I coordinate scheduling improvements and build tools for team projects.")
interview = checked(Interviews::StartDemoService.call(user: user, execution_mode: "real"))
puts "VERIFICATION_SESSION_ID=#{interview.id}"
await_paid(interview.operations.preparation.first)
interview = checked(Interviews::BeginService.call(interview: interview))
await_paid(interview.operations.speech.first)
# Input files are generated by the documented offline Docker command, never paid seed speech.
ARGV.each do |path|
  interview.reload
  break if interview.completed?
  bytes = File.binread(path)
  question = interview.questions.find_by!(position: interview.current_question_position)
  receipt = checked(Interviews::ReserveRecordingService.call(interview: interview, question_id: question.id,
    expected_revision: interview.revision, content_type: "audio/wav", byte_size: bytes.bytesize,
    checksum: Digest::MD5.base64digest(bytes)))
  uri = URI(receipt[:upload_url])
  response = Net::HTTP.start(uri.host, uri.port, open_timeout: 3, read_timeout: 5) do |http|
    http.request(Net::HTTP::Put.new(uri, receipt[:headers]).tap { |request| request.body = bytes })
  end
  raise "Upload failed" unless response.code == "200"
  media = InterviewSessionMedia.find(receipt[:media_id])
  checked(Interviews::RegisterMediaService.call(media: media))
  operation = checked(Interviews::SubmitTurnService.call(interview: interview, question_id: question.id,
    recording_id: media.id, expected_revision: interview.revision, submission_key: SecureRandom.uuid))
  await_paid(operation)
  puts "SYNTHETIC_DIALOGUE=#{interview.messages.order(:position).pluck(:kind, :content).to_json}"
  await_paid(interview.operations.speech.order(:created_at).last)
end
ledger("final")
